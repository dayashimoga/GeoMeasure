import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../../../core/config/app_config.dart';
import '../../../core/di/service_locator.dart';
import '../../measurement_engine/domain/entities/measurement_algorithm.dart';
import '../../measurement_engine/domain/entities/spatial_shape.dart';
import '../../measurement_engine/domain/services/unit_converter.dart';
import '../../measurement_engine/domain/services/svg_exporter.dart';
import '../../measurement_engine/domain/services/kml_exporter.dart';
import '../../export/excel_exporter.dart';

/// Reusable export buttons panel for measurement results.
///
/// Provides DXF, CSV, SVG, GeoJSON, KML, JSON, Excel, and PDF exports.
class ExportPanel extends StatelessWidget {
  const ExportPanel({super.key});

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Card(
      elevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(16),
        side: BorderSide(color: theme.colorScheme.outlineVariant),
      ),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'EXPORT REPORTS & CAD',
              style: TextStyle(
                fontSize: 11,
                fontWeight: FontWeight.w600,
                letterSpacing: 1.2,
                color: theme.colorScheme.onSurface.withValues(alpha: 0.5),
              ),
            ),
            const SizedBox(height: 12),
            Wrap(
              spacing: 8,
              runSpacing: 8,
              children: [
                _chip(context, 'PDF', Icons.picture_as_pdf_rounded, () {
                  final result = sl.measurementProvider.lastResult;
                  if (result == null) return;
                  _showExport(
                    context,
                    'PDF Report',
                    'Measurement: ${result.shapeName.isEmpty ? result.shapeType : result.shapeName}\n'
                        'Area: ${result.area.toStringAsFixed(3)} ${UnitConverter.areaUnitLabel(result.areaUnit)}\n'
                        'Perimeter: ${result.perimeter.toStringAsFixed(3)} ${UnitConverter.distanceUnitLabel(result.distanceUnit)}\n'
                        '${result.volume > 0 ? 'Volume: ${result.volume.toStringAsFixed(3)} m³\n' : ''}'
                        'Algorithm: ${result.algorithmUsed.displayName}\n'
                        'Accuracy: ${result.estimatedAccuracyPercentage.toStringAsFixed(0)}%\n'
                        '\nGenerated by GeoMeasure ${AppConfig.appVersion}',
                  );
                }),
                _chip(context, 'DXF', Icons.architecture_rounded, () {
                  final str = sl.measurementProvider.exportCurrentToDxf();
                  if (str.isEmpty) return;
                  _showExport(context, 'AutoCAD DXF', str);
                }),
                _chip(context, 'CSV', Icons.table_chart_rounded, () {
                  final str = sl.measurementProvider.exportHistoryToCsv();
                  if (str.isEmpty) return;
                  _showExport(context, 'CSV Schedule', str);
                }),
                _chip(context, 'SVG', Icons.image_rounded, () {
                  final shape = sl.measurementProvider.lastShape;
                  if (shape == null) return;
                  _showExport(context, 'SVG Floor Plan',
                      SvgExporter.generateSvg(shape));
                }),
                _chip(context, 'GeoJSON', Icons.public_rounded, () {
                  final str = sl.measurementProvider.exportPlotToGeoJson();
                  _showExport(
                      context,
                      'GeoJSON',
                      str.isNotEmpty
                          ? str
                          : 'GeoJSON requires Land (GPS) measurement data.');
                }),
                _chip(context, 'KML', Icons.map_rounded, () {
                  final shape = sl.measurementProvider.lastShape;
                  if (shape is PlotShape) {
                    _showExport(context, 'KML (Google Earth)',
                        KmlExporter.generateKml(shape));
                  } else {
                    _showExport(context, 'KML',
                        'KML requires Land (GPS) measurement data.');
                  }
                }),
                _chip(context, 'JSON', Icons.data_object_rounded, () {
                  final result = sl.measurementProvider.lastResult;
                  if (result != null) {
                    _showExport(context, 'JSON', result.toJson().toString());
                  }
                }),
                _chip(context, 'Excel', Icons.grid_on_rounded, () {
                  final history = sl.measurementProvider.history;
                  if (history.isEmpty) return;
                  final bytes = ExcelExporter.exportMeasurements(history);
                  _showExport(
                    context,
                    'Excel (XLSX)',
                    'Generated ${bytes.length} bytes XLSX with ${history.length} measurements.\n\n'
                        'Copy the Base64 below to decode into a .xlsx file:\n\n'
                        '${base64Encode(bytes)}',
                  );
                }),
              ],
            ),
          ],
        ),
      ),
    );
  }

  Widget _chip(
      BuildContext context, String label, IconData icon, VoidCallback onTap) {
    return ActionChip(
      avatar: Icon(icon, size: 16),
      label: Text(label, style: const TextStyle(fontSize: 13)),
      onPressed: onTap,
    );
  }

  void _showExport(BuildContext context, String title, String content) {
    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Row(
          children: [
            Icon(Icons.file_download_outlined,
                size: 22, color: Theme.of(context).colorScheme.primary),
            const SizedBox(width: 8),
            Expanded(child: Text(title)),
          ],
        ),
        content: SizedBox(
          width: double.maxFinite,
          child: SingleChildScrollView(
            child: SelectableText(
              content,
              style: TextStyle(
                fontFamily: 'monospace',
                fontSize: 11,
                color: Theme.of(context)
                    .colorScheme
                    .onSurface
                    .withValues(alpha: 0.8),
              ),
            ),
          ),
        ),
        actions: [
          TextButton.icon(
            icon: const Icon(Icons.copy_rounded, size: 16),
            onPressed: () {
              Clipboard.setData(ClipboardData(text: content)).then((_) {
                if (ctx.mounted) {
                  ScaffoldMessenger.of(ctx).showSnackBar(
                    SnackBar(
                      content: Text('$title copied to clipboard'),
                      behavior: SnackBarBehavior.floating,
                      duration: const Duration(seconds: 2),
                    ),
                  );
                }
              });
            },
            label: const Text('Copy'),
          ),
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }
}
